begin;
create extension if not exists pgtap with schema extensions;
set local search_path=public,extensions;
select no_plan();
select is(app_internal.public_staging_ready('https://staging.example.test'),false,'staging closed by default');
select ok(not has_table_privilege('app_server','app.public_booking_runtime','UPDATE'),'backend cannot open gate');
select ok(not has_function_privilege('anon','app_internal.public_staging_ready(text)','EXECUTE'),'anon has no staging RPC');
select ok(not has_function_privilege('authenticated','app_internal.public_staging_ready(text)','EXECUTE'),'members have no staging RPC');
select ok(not has_function_privilege('service_role','app_internal.public_staging_ready(text)','EXECUTE'),'service role not broadened');
select ok(has_function_privilege('app_server','app_internal.public_staging_ready(text)','EXECUTE'),'backend can check staging');
select throws_ok($$update app.public_booking_runtime set staging_enabled=true$$,'23514',null,'incomplete gate cannot open');
update app.public_booking_runtime set staging_enabled=true,staging_origin='https://staging.example.test',staging_until=clock_timestamp()+interval '1 hour';
select is(app_internal.public_staging_ready('https://staging.example.test'),true,'exact origin enabled temporarily');
select is(app_internal.public_runtime_ready(),false,'staging does not impersonate discarded mode');
select is(app_internal.public_staging_ready('https://other.example.test'),false,'other origin denied');
select lives_ok('select app.require_disposable_public()','shared SQL gate accepts enabled staging');
select ok(exists(select 1 from public.audit_logs where action='public_staging.configured' and actor_type='system' and after_data->>'database_role'=session_user),'maintenance gate changes audited');
update app.public_booking_runtime set staging_until=clock_timestamp()-interval '1 second';
select is(app_internal.public_staging_ready('https://staging.example.test'),false,'expired gate denied');
select throws_ok('select app.require_disposable_public()','PT503','PUBLIC_BOOKING_DISABLED','SQL commands fail closed on expiry');
update app.public_booking_runtime set staging_until=clock_timestamp()+interval '25 hours';
select is(app_internal.public_staging_ready('https://staging.example.test'),false,'unbounded enablement denied');
update app.public_booking_runtime set staging_enabled=false;
select is(app_internal.public_staging_ready('https://staging.example.test'),false,'explicit closure denied');
select * from finish();
rollback;
